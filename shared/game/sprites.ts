/**
 * Every character, good and building in the game, as small vector drawings. One source for both
 * places they appear: the board draws them once into bitmaps (app/game/renderer.ts) and copies those
 * every frame, and the interface shows them as inline SVG (app/components/SpriteIcon.vue).
 *
 * An op is one shape in the sprite's own coordinates (its view box):
 *   ['p', svgPath, fill, stroke?, lineWidth?, alpha?]
 *   ['c', cx, cy, r, fill, stroke?, lineWidth?, alpha?]
 *   ['e', cx, cy, rx, ry, fill, stroke?, lineWidth?, alpha?]
 *   ['r', x, y, w, h, radius, fill, stroke?, lineWidth?, alpha?]
 * A null fill draws only the outline. Strokes have round caps and joins. Animals face right.
 */

type Paint = string | null
type Style = [fill: Paint, stroke?: Paint, lineWidth?: number, alpha?: number]
export type SpriteOp
  = | ['p', string, ...Style]
    | ['c', number, number, number, ...Style]
    | ['e', number, number, number, number, ...Style]
    | ['r', number, number, number, number, number, ...Style]

export interface SpriteDef {
  /** View box width and height. */
  vw: number
  vh: number
  /** Size drawn on the board, in board units (anchored at the bottom centre). */
  w: number
  h: number
  ops: SpriteOp[]
}

